local N=require "lightWorks/lightWorks_Notifications"
assert(N.observers.publish==nil,"observer facade must not expose producer helpers")
local first,second=0,0
N.subscribe("*","mutating-view",function(e)e.detail.value=99;e.subject.id="changed";first=first+1 end)
N.subscribe("world","safe-view",function(e)assert(e.detail.value==1 and e.subject.id=="42");second=second+1 end)
N.subscribe("world","bad-listener",function()error("deliberate listener failure")end)
assert(N.publish("world","activation",{kind="item",id="42"},{value=1}))
assert(first==1 and second==1 and N.status().listenerFailures==1)
assert(N.status().lastFailure.error:find("deliberate listener failure",1,true))
local status=N.status();status.lastFailure.error="tampered";assert(N.status().lastFailure.error~="tampered")
assert(not N.subscribe("world","safe-view",function()end))
assert(not N.subscribe("unknown","id",function()end))
assert(not N.publish("world","invalid",{kind="item",object={}},{value=1}))
assert(not N.publish("world","invalid",{kind="item"},{value=0/0}))
assert(N.unsubscribe("*","mutating-view") and N.unsubscribe("world","safe-view") and N.unsubscribe("world","bad-listener"))
N.subscribe("world","unprintable-error",function()error(setmetatable({},{__tostring=function()error("unprintable")end}))end)
assert(N.publish("world","malformed-listener-error",{kind="item"}))
assert(N.status().lastFailure.error=="listener error could not be formatted")
N.unsubscribe("world","unprintable-error")
local old=N.subscribe("world","reload-owner",function()end)
assert(N.unsubscribe("world","reload-owner",old))
local replacement=N.subscribe("world","reload-owner",function()end)
assert(not N.unsubscribe("world","reload-owner",old) and N.unsubscribe("world","reload-owner",replacement),
    "stale teardown token must not remove a replacement subscription")
assert(not N.unsubscribe("world","bad-listener"))
local later=0
N.subscribe("registry","first",function()
    N.unsubscribe("registry","removed-before-turn")
    N.subscribe("registry","added-during-delivery",function()later=later+1 end)
end)
N.subscribe("registry","removed-before-turn",function()error("must be skipped")end)
assert(N.publish("registry","providerRegistered",{kind="provider",id="fixture"}))
assert(later==0)
N.publish("registry","providerRegistered",{kind="provider",id="fixture"});assert(later==1)
N.unsubscribe("registry","first");N.unsubscribe("registry","added-during-delivery")
for i=1,64 do assert(N.subscribe("world","cap"..i,function()end))end
assert(not N.subscribe("world","overflow",function()end))
for i=1,64 do assert(N.unsubscribe("world","cap"..i))end
local delivered=0
N.subscribe("world","loop",function()delivered=delivered+1;N.publish("world","nested",{kind="item"})end)
assert(N.publish("world","start",{kind="item"}))
assert(delivered==N.MAX_DELIVERY and N.status().dropped>0,"nested publication must drain under a hard budget")
N.unsubscribe("world","loop")
assert(N.publish("world","after-budget",{kind="item"}),"budget exhaustion must not poison future dispatch")
print("notification isolation, unsubscribe lifecycle, registration budget and reentrant FIFO limits pass")
